# ─── Public API ───────────────────────────────────────────────────────────────

class ExportService:
    """Converts a :class:`ProjectContext` into an IEEE styled PDF document."""

    def generate_pdf(self, context: ProjectContext) -> bytes:
        buffer = io.BytesIO()
        styles = _build_styles()

        project_name = "BLUEPRINT PLAN"
        if context.requirements and context.requirements.project_name:
            project_name = context.requirements.project_name

        doc = BaseDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=MARGIN,
            rightMargin=MARGIN,
            topMargin=MARGIN,
            bottomMargin=MARGIN,
            title=f"IEEE SPECIFICATION: {project_name.upper()}",
            author="BluePrint AI Planner",
        )
        doc._project_name = project_name

        body_frame  = Frame(MARGIN, MARGIN, PAGE_W - 2 * MARGIN, PAGE_H - 2 * MARGIN)
        body_tpl  = PageTemplate(id="IEEE_Body", frames=[body_frame], onPage=_on_body_page)
        doc.addPageTemplates([body_tpl])

        story: List[Flowable] = []
        story.append(NextPageTemplate("IEEE_Body"))
        
        # Cover sheet / Abstract
        story.extend(_build_cover(context, styles))
        
        # Table of Contents
        story.extend(_build_toc(context, styles))

        if context.requirements:
            story.extend(_build_requirements_section(context.requirements, styles))

        if context.architecture:
            story.extend(_build_architecture_section(context.architecture, styles))

        if context.database:
            story.extend(_build_database_section(context.database, styles))

        if context.documentation:
            story.extend(_build_documentation_section(context.documentation, styles))

        doc.build(story)
        return buffer.getvalue()
