# ─── Custom IEEE Page Borders and Canvas Callbacks ──────────────────────────

def _on_first_page(canvas, doc):
    """Draws simple cover borders/headers if necessary."""
    canvas.saveState()
    canvas.restoreState()


def _on_body_page(canvas, doc):
    """Draws the running headers/footers in traditional IEEE technical report style."""
    canvas.saveState()
    canvas.setStrokeColor(colors.HexColor("#7F8C8D"))
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, PAGE_H - 1.5 * cm, PAGE_W - MARGIN, PAGE_H - 1.5 * cm)
    
    # Running header
    canvas.setFillColor(colors.HexColor("#555555"))
    canvas.setFont("Times-Roman", 8)
    project = getattr(doc, "_project_name", "BLUEPRINT PROJECT REPORT")
    canvas.drawString(MARGIN, PAGE_H - 1.3 * cm, f"IEEE DESIGN SPECIFICATION: {project.upper()}")
    
    # Footer
    canvas.line(MARGIN, 1.5 * cm, PAGE_W - MARGIN, 1.5 * cm)
    canvas.drawString(MARGIN, 1.1 * cm, "Generated by BluePrint AI — SDLC Planner")
    canvas.drawRightString(PAGE_W - MARGIN, 1.1 * cm, f"Page {doc.page}")
    canvas.restoreState()


