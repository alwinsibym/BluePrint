# ─── Content Helper Builders ────────────────────────────────────────────────

def _p(text: str, style: ParagraphStyle) -> Paragraph:
    safe = (text or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return Paragraph(safe, style)


def _bullet_list(items: List[str], styles: dict) -> List[Flowable]:
    out: List[Flowable] = []
    for item in items:
        safe = (item or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        out.append(Paragraph(f"• {safe}", styles["bullet"]))
    return out


def _section_header(numeral: str, title: str, styles: dict) -> List[Flowable]:
    return [
        Spacer(1, 0.4 * cm),
        _p(f"{numeral}. {title.upper()}", styles["section_heading"]),
        Spacer(1, 0.2 * cm),
    ]


def _sub_header(letter: str, title: str, styles: dict) -> Flowable:
    return _p(f"{letter}. {title}", styles["sub_heading"])


def _code_block(sql: str, styles: dict) -> List[Flowable]:
    lines = (sql or "").split("\n")
    out = []
    for line in lines:
        safe = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        out.append(Paragraph(safe or "&nbsp;", styles["code"]))
    return out


def _build_cover(context: ProjectContext, styles: dict) -> List[Flowable]:
    project_name = "UNTITLED SYSTEM SPECIFICATION"
    overview = "This document presents the design specification, architecture, and database design produced under IEEE standards."
    if context.requirements:
        project_name = (context.requirements.project_name or project_name).upper()
        overview = context.requirements.project_overview or overview

    now = datetime.now().strftime("%B %d, %Y")

    flowables: List[Flowable] = [
        Spacer(1, 3 * cm),
        _p(project_name, styles["ieee_title"]),
        _p("SYSTEM ENGINEERING BLUEPRINT AND SRS DOCUMENTATION", styles["ieee_subtitle"]),
        Spacer(1, 1 * cm),
        _p("Prepared by: BluePrint Automated SDLC Agent Suite<br/>"
           f"Date: {now}<br/>"
           "Standards Compliance: IEEE Std 830-1998 / ISO 12207", styles["ieee_author"]),
        Spacer(1, 1.5 * cm),
        _p("Abstract", styles["ieee_abstract_label"]),
        _p(overview, styles["ieee_abstract_text"]),
        PageBreak(),
    ]
    return flowables


def _build_toc(context: ProjectContext, styles: dict) -> List[Flowable]:
    out: List[Flowable] = _section_header("I", "Table of Contents", styles)
    out.append(Spacer(1, 0.5 * cm))
    
    sections = []
    if context.requirements:  sections.append("II. Software Requirements Specification (SRS)")
    if context.architecture:  sections.append("III. System Architecture Design")
    if context.database:      sections.append("IV. Database Design and Schema Normalization")
    if context.documentation: sections.append("V. System Execution and Reference Documentation")

    for s in sections:
        out.append(_p(s, styles["toc_item"]))
        out.append(Spacer(1, 0.2 * cm))
    out.append(PageBreak())
    return out


def _build_requirements_section(req, styles: dict) -> List[Flowable]:
    out: List[Flowable] = _section_header("II", "Software Requirements Specification", styles)

    out.append(_sub_header("A", "Project Scope and Overview", styles))
    out.append(_p(req.project_overview, styles["body"]))
    out.append(Spacer(1, 0.3 * cm))

    if req.objectives:
        out.append(_sub_header("B", "System Objectives", styles))
        out.extend(_bullet_list(req.objectives, styles))
        out.append(Spacer(1, 0.3 * cm))

    if req.functional_requirements:
        out.append(_sub_header("C", "Functional Requirements", styles))
        out.extend(_bullet_list(req.functional_requirements, styles))
        out.append(Spacer(1, 0.3 * cm))

    if req.non_functional_requirements:
        out.append(_sub_header("D", "Non-Functional Requirements", styles))
        out.extend(_bullet_list(req.non_functional_requirements, styles))
        out.append(Spacer(1, 0.3 * cm))

    if req.user_roles:
        out.append(_sub_header("E", "User Roles & Personas", styles))
        out.extend(_bullet_list(req.user_roles, styles))
        out.append(Spacer(1, 0.3 * cm))

    if req.user_stories:
        out.append(_sub_header("F", "Use Case / User Story Breakdown", styles))
        out.append(_p("<b>TABLE I. USER STORY SPECIFICATION</b>", styles["body_bold"]))
        table_data = [["Role", "Desire", "Benefit"]]
        for story in req.user_stories:
            table_data.append([
                Paragraph(story.role or "", styles["body"]),
                Paragraph(story.desire or "", styles["body"]),
                Paragraph(story.benefit or "", styles["body"]),
            ])
        col_widths = [3 * cm, 7.5 * cm, 6 * cm]
        t = Table(table_data, colWidths=col_widths, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND",  (0, 0), (-1, 0), colors.HexColor("#EAECEE")),
            ("TEXTCOLOR",   (0, 0), (-1, 0), colors.black),
            ("FONTNAME",    (0, 0), (-1, 0), "Times-Bold"),
            ("FONTSIZE",    (0, 0), (-1, 0), 10),
            ("ALIGN",       (0, 0), (-1, 0), "LEFT"),
            ("GRID",        (0, 0), (-1, -1), 0.5, colors.HexColor("#BDC3C7")),
            ("TOPPADDING",  (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        out.append(t)
        out.append(Spacer(1, 0.5 * cm))

    if req.recommended_tech_stack:
        out.append(_sub_header("G", "Technology Stack Composition", styles))
        ts = req.recommended_tech_stack
        stack_data = [
            ["Layer", "Technology Profile"],
            ["Frontend Client",   ts.frontend   or "—"],
            ["Backend Application",    ts.backend    or "—"],
            ["Database Server",   ts.database   or "—"],
            ["Inference Engine",   ts.ai_framework or "—"],
        ]
        t2 = Table(stack_data, colWidths=[5 * cm, 11.5 * cm], repeatRows=1)
        t2.setStyle(TableStyle([
            ("BACKGROUND",  (0, 0), (-1, 0), colors.HexColor("#EAECEE")),
            ("TEXTCOLOR",   (0, 0), (-1, 0), colors.black),
            ("FONTNAME",    (0, 0), (-1, 0), "Times-Bold"),
            ("GRID",        (0, 0), (-1, -1), 0.5, colors.HexColor("#BDC3C7")),
            ("TOPPADDING",  (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        out.append(t2)
        out.append(Spacer(1, 0.4 * cm))

    if req.assumptions or req.constraints:
        out.append(_sub_header("H", "Assumptions and Constraints", styles))
        if req.assumptions:
            out.append(_p("<b>System Assumptions:</b>", styles["body_bold"]))
            out.extend(_bullet_list(req.assumptions, styles))
        if req.constraints:
            out.append(_p("<b>System Constraints:</b>", styles["body_bold"]))
            out.extend(_bullet_list(req.constraints, styles))

    out.append(PageBreak())
    return out


def _build_architecture_section(arch, styles: dict) -> List[Flowable]:
    out: List[Flowable] = _section_header("III", "System Architecture Design", styles)

    out.append(_sub_header("A", "High-Level Architecture Description", styles))
    out.append(_p(arch.high_level_architecture, styles["body"]))
    out.append(Spacer(1, 0.3 * cm))

    if arch.data_flow:
        out.append(_sub_header("B", "Information Flow & Core Mechanics", styles))
        out.append(_p(arch.data_flow, styles["body"]))
        out.append(Spacer(1, 0.3 * cm))

    if arch.folder_structure:
        out.append(_sub_header("C", "Logical Project Directory Structure", styles))
        out.extend(_code_block("\n".join(arch.folder_structure), styles))
        out.append(Spacer(1, 0.3 * cm))

    if arch.component_breakdown:
        out.append(_sub_header("D", "Component Decomposition", styles))
        for comp in arch.component_breakdown:
            out.append(_p(f"<b>Component: {comp.name}</b>", styles["body_bold"]))
            out.append(_p(comp.description or "", styles["body"]))
            if comp.dependencies:
                out.append(_p(f"<i>Dependencies:</i> {', '.join(comp.dependencies)}", styles["body"]))
            out.append(Spacer(1, 0.2 * cm))

    out.append(PageBreak())
    return out


def _build_database_section(db, styles: dict) -> List[Flowable]:
    out: List[Flowable] = _section_header("IV", "Database Design and Schema Normalization", styles)

    if db.database_overview:
        out.append(_sub_header("A", "Database Overview", styles))
        out.append(_p(db.database_overview, styles["body"]))
        out.append(Spacer(1, 0.3 * cm))

    if db.normalization_notes:
        out.append(_sub_header("B", "Normalization and Integrity Constraints", styles))
        out.append(_p(db.normalization_notes, styles["body"]))
        out.append(Spacer(1, 0.3 * cm))

    if db.relationships:
        out.append(_sub_header("C", "Entity-Relationship Cardinalities", styles))
        out.extend(_bullet_list(db.relationships, styles))
        out.append(Spacer(1, 0.3 * cm))

    if db.entities:
        out.append(_sub_header("D", "Entity Specifications", styles))
        for entity in db.entities:
            out.append(_p(f"<b>Table Schema: {entity.name}</b>", styles["body_bold"]))
            out.append(_p(entity.description or "", styles["body"]))
            if entity.attributes:
                attr_data = [["Attribute / Field"]]
                for attr in entity.attributes:
                    attr_data.append([Paragraph(attr or "", styles["body"])])
                t = Table(attr_data, colWidths=[PAGE_W - 2 * MARGIN - 1 * cm], repeatRows=1)
                t.setStyle(TableStyle([
                    ("BACKGROUND",  (0, 0), (-1, 0), colors.HexColor("#EAECEE")),
                    ("GRID",        (0, 0), (-1, -1), 0.5, colors.HexColor("#BDC3C7")),
                    ("TOPPADDING",  (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]))
                out.append(t)
            
            pk_text = f"Primary Key: {entity.primary_key}" if entity.primary_key else ""
            fk_text = f"Foreign Keys: {', '.join(entity.foreign_keys)}" if entity.foreign_keys else ""
            if pk_text or fk_text:
                out.append(_p(f"<i>Keys:</i> {pk_text} { ' | ' + fk_text if fk_text else ''}", styles["body"]))
            out.append(Spacer(1, 0.4 * cm))

    if db.sql_schema:
        out.append(_sub_header("E", "ANSI-Compliant DDL Statements", styles))
        out.extend(_code_block(db.sql_schema, styles))

    out.append(PageBreak())
    return out


